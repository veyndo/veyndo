/** The component catalog: generated artifacts match the one source; every entry's contract, examples and safety refusals hold. */
import { readFileSync, writeFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import { format } from "prettier";
import { describe, expect, it } from "vitest";
import {
  CatalogView,
  catalogDocument,
  catalogId,
  catalogVersion,
  entries,
  exampleAdmission,
  exampleDocument,
  propTypesSource,
  sampleText,
  typeLabel,
} from "../../src/kit/catalog";

// Tests run from frontend/.
const write = Boolean(process.env.WRITE_COMPONENT_CATALOG);
const files = {
  catalog: "src/kit/catalog/catalog.json",
  types: "src/kit/ui/props.generated.ts",
  gallery: "../docs/component-gallery.md",
};

/** The handbook page: contract tables and static renders of every example (light/English, dark/German). */
function galleryPage() {
  const css = [
    "src/kit/tokens/tokens.css",
    "src/kit/ui/ui.css",
    "src/kit/storefront/storefront.css",
    "src/kit/catalog/catalog.css",
  ]
    .map((file) => readFileSync(file, "utf8"))
    .join("\n")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\n\s*\n/g, "\n");
  const contract = catalogDocument(sampleText("en-GB"));
  const cell = (value: string) => value.replaceAll("|", "\\|");
  const out = [
    "# Component gallery",
    "",
    `<!-- Generated by \`WRITE_COMPONENT_CATALOG=1 npm test -- component-catalog\` from frontend/src/kit/catalog; do not edit. -->`,
    "",
    `Catalog \`${catalogId}\`, version ${catalogVersion}. Each component of the`,
    "[design system](design-system.md) with its document props, slots, events,",
    "accessibility contract and examples. The examples below are rendered from",
    "their documents by the same renderer that Studio, the storefront, app",
    "surfaces and MCP Apps use: on the left in the light theme with English",
    "samples, on the right in the dark theme with German samples. Studio shows",
    "the interactive gallery under **Developer → Components**, with every",
    "shipped language. The machine-readable catalog is",
    "[`catalog.json`](../frontend/src/kit/catalog/catalog.json).",
    "",
    "<style>",
    css.trim(),
    ".vy-gallery-frames{margin:0 0 1.5rem}",
    "</style>",
    "",
  ];
  for (const entry of contract.entries) {
    const source = entries.find((candidate) => candidate.name === entry.name)!;
    out.push(`## ${entry.name}`, "", entry.description, "");
    out.push(
      `**Kind** ${entry.kind} · **Source** \`${entry.source}\` · **Since** ${entry.since} · **Surfaces** ${
        entry.surfaces.length ? entry.surfaces.join(", ") : "none (code only)"
      }`,
      "",
    );
    if (entry.codeOnly) out.push(`Code only: ${entry.codeOnly}`, "");
    const properties = (entry.props.properties ?? {}) as Record<
      string,
      Record<string, unknown>
    >;
    const required = new Set((entry.props.required ?? []) as string[]);
    if (Object.keys(properties).length) {
      out.push(
        "| Prop | Type | Required | Default |",
        "| --- | --- | --- | --- |",
      );
      for (const [name, schema] of Object.entries(properties))
        out.push(
          `| \`${name}\`${entry.hostData?.includes(name) ? " (host data)" : ""} | ${cell(typeLabel(schema))} | ${
            required.has(name) ? "yes" : "no"
          } | ${schema.default === undefined ? "" : cell(`\`${JSON.stringify(schema.default)}\``)} |`,
        );
      out.push("");
    }
    for (const [slot, rule] of Object.entries(entry.slots))
      out.push(
        `- Slot \`${slot}\`: ${rule.description} Accepts ${
          Array.isArray(rule.accepts)
            ? rule.accepts.map((name) => `\`${name}\``).join(", ")
            : rule.accepts
        }${rule.max !== undefined ? `, at most ${rule.max}` : ""}.`,
      );
    for (const [event, rule] of Object.entries(entry.events))
      out.push(`- Event \`${event}\`: ${rule.description}`);
    const a11y = entry.a11y;
    out.push(
      `- Accessibility: ${a11y.role ? `role \`${a11y.role}\`; ` : ""}${
        a11y.pattern ? `pattern ${a11y.pattern}; ` : ""
      }${a11y.keyboard ? `keys ${a11y.keyboard.join(", ")}; ` : ""}${a11y.notes}`,
      "",
    );
    for (const example of source.examples) {
      out.push(`### ${entry.name}: ${example.state}`, "");
      const frames = (["light", "dark"] as const).map((theme) => {
        const locale = theme === "light" ? "en-GB" : "de-DE";
        const markup = renderToStaticMarkup(
          <CatalogView
            document={exampleDocument(example, locale)}
            admission={exampleAdmission(source, example, locale)}
            onAction={() => undefined}
          />,
          // Every render on the one page needs its own element ids.
          { identifierPrefix: `${entry.name}-${example.id}-${theme}-` },
        );
        // Shop-relative links have no target in the handbook; the renders stay inert.
        const inert = markup.replace(/ href="[^"]*"/g, "");
        return `<div class="vy-gallery-frame" data-theme="${theme}">${inert}</div>`;
      });
      out.push(`<div class="vy-gallery-frames">${frames.join("")}</div>`, "");
      out.push(
        "<details><summary>Document</summary>",
        "",
        "```json",
        JSON.stringify(exampleDocument(example, "en-GB"), null, 2),
        "```",
        "",
        "</details>",
        "",
      );
    }
  }
  return out.join("\n");
}

describe("generated catalog artifacts", () => {
  it("match the catalog source (WRITE_COMPONENT_CATALOG=1 regenerates)", async () => {
    const catalog = catalogDocument(sampleText("en-GB"));
    const types = await format(propTypesSource(), { parser: "typescript" });
    const gallery = galleryPage();
    if (write) {
      writeFileSync(
        files.catalog,
        await format(JSON.stringify(catalog), { parser: "json" }),
      );
      writeFileSync(files.types, types);
      writeFileSync(files.gallery, gallery);
    }
    // The JSON is compared as data; Prettier owns its layout.
    expect(JSON.parse(readFileSync(files.catalog, "utf8"))).toEqual(
      JSON.parse(JSON.stringify(catalog)),
    );
    expect(readFileSync(files.types, "utf8")).toBe(types);
    expect(readFileSync(files.gallery, "utf8")).toBe(gallery);
  });
});
