/** Generate the design token stylesheet from tokens.json; --check fails when the committed stylesheet differs. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
export const tokenDir = path.resolve(import.meta.dirname, "../src/kit/tokens");
/** The stylesheet text that tokens.json defines. */
export function renderTokens() {
  const tokens = JSON.parse(
    fs.readFileSync(path.join(tokenDir, "tokens.json"), "utf8"),
  );
  const flat = (group) =>
    Object.entries(tokens[group])
      .filter(([key]) => group !== "shadow" || !key.endsWith("-dark"))
      .map(([key, value]) =>
        // Match Prettier's wrapping so the formatted file stays byte-identical.
        `  --vy-${group}-${key}: ${value};`.length > 80
          ? `  --vy-${group}-${key}:\n    ${value};`
          : `  --vy-${group}-${key}: ${value};`,
      );
  const colors = (scheme) =>
    Object.entries(tokens.color[scheme]).map(
      ([key, value]) => `  --vy-color-${key}: ${value};`,
    );
  const dark = [
    ...colors("dark"),
    `  --vy-shadow-lg: ${tokens.shadow["lg-dark"]};`,
    "  color-scheme: dark;",
  ];
  return [
    "/* Generated by scripts/tokens.mjs from tokens.json; do not edit. Design tokens for every Veyndo surface. */",
    ":root,",
    '[data-theme="light"] {',
    ...colors("light"),
    ...["space", "radius", "font", "shadow", "motion"].flatMap(flat),
    "  color-scheme: light;",
    "}",
    "@media (prefers-color-scheme: dark) {",
    '  [data-theme="system"] {',
    ...dark.map((line) => "  " + line),
    "  }",
    "}",
    '[data-theme="dark"] {',
    ...dark,
    "}",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    "    --vy-motion-fast: 0ms;",
    "    --vy-motion-base: 0ms;",
    "  }",
    "}",
    "",
  ].join("\n");
}
/** Null when tokens.css matches tokens.json, otherwise the error to report. */
export function tokenDrift() {
  const target = path.join(tokenDir, "tokens.css");
  return fs.existsSync(target) &&
    fs.readFileSync(target, "utf8") === renderTokens()
    ? null
    : "kit/tokens/tokens.css differs from tokens.json; run node scripts/tokens.mjs";
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const drift = tokenDrift();
    if (drift) {
      console.error(drift);
      process.exit(1);
    }
    console.log("PASS design tokens: tokens.css matches tokens.json");
  } else fs.writeFileSync(path.join(tokenDir, "tokens.css"), renderTokens());
}
