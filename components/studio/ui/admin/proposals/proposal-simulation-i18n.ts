export type ProposalSimulationWord = keyof typeof words;
/** The words of the proposal twin review in the current interface language. */
export function useProposalSimulationText() {
  const { locale } = useLocale();
  const index =
    ({ en: 0, de: 1, fr: 2, es: 3 } as Record<string, number>)[
      locale.slice(0, 2)
    ] ?? 0;
  const word = (key: ProposalSimulationWord) => words[key][index];
  /** A word for a stable server code, or the code itself when a newer server sends one this interface does not know. */
  const code = (prefix: string, value: string | null | undefined) =>
    value && `${prefix}_${value}` in words
      ? words[`${prefix}_${value}` as ProposalSimulationWord][index]
      : (value ?? "");
  return { word, code, locale };
}
