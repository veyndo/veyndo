"""Render docs/proof-coverage.md from proof/manifest.json and the kernel sources; --check rejects drift and broken totals."""
from pathlib import Path
import argparse, json, re, sys

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / 'proof/manifest.json'
KERNEL = ROOT / 'crates/kernel/src/verified_kernel'
PAGE = ROOT / 'docs/proof-coverage.md'
SOURCE = 'https://github.com/veyndo/veyndo/blob/main/'
DOMAINS = {
    'commerce': 'Prices, stock, payments and refunds',
    'fulfillment': 'Orders, delivery and returns',
    'access': 'Rights, shops and sessions',
    'agents': 'Agent budgets',
    'intelligence': 'AI prices, claims and experiments',
    'automation': 'Rules and flows',
    'apps': 'Apps and their sandbox',
}
# The money path: every file a price, an order total or a payment passes through.
MONEY = [
    ('Money primitives and discounts', lambda p: p.startswith('crates/commerce/src/')),
    ('Cart and prices', lambda p: re.match(r'src/cart_\w+\.rs$', p) is not None),
    ('Checkout and orders', lambda p: p.startswith('src/checkout/') or re.match(r'src/(checkout_\w+|order_\w+)\.rs$', p) is not None),
    ('Payments and refunds', lambda p: p.startswith('src/payments/')),
    ('Currencies and taxes', lambda p: p.startswith('src/currencies/') or re.match(r'src/commerce/tax\w*\.rs$', p) is not None),
    ('Stock', lambda p: re.match(r'src/commerce/inventory\w*\.rs$', p) is not None),
]
STATUS = ('extracted-policy', 'reviewed-binding', 'conformance-driver', 'unproved')


def rules():
    """Every extracted rule with its domain and the sentence written above it in the production source."""
    found = {}
    for path in sorted(KERNEL.glob('*.rs')):
        note = ''
        for line in path.read_text().splitlines():
            if line.startswith('///'):
                note = (note + ' ' + line[3:].strip()).strip()
                continue
            match = re.match(r'pub fn (\w+)', line)
            if match:
                found[match.group(1)] = (path.stem, note)
            if not line.startswith('#['):
                note = ''
    return found


def counts(manifest):
    result = {status: 0 for status in STATUS}
    for entry in manifest['sources'].values():
        result[entry['status']] += 1
    return result


def errors(manifest, found):
    problems = []
    if set(found) != set(manifest['policies']):
        problems.append('kernel rules and manifest policies differ: ' + str(sorted(set(found) ^ set(manifest['policies']))))
    unknown = {entry['status'] for entry in manifest['sources'].values()} - set(STATUS)
    if unknown:
        problems.append('unknown source status: ' + str(sorted(unknown)))
    for name, policy in manifest['policies'].items():
        if not policy['theorems']:
            problems.append(name + ': a listed rule needs at least one proved property')
        for binding in policy['bindings']:
            if manifest['sources'].get(binding, {}).get('status') not in ('reviewed-binding', 'extracted-policy'):
                problems.append(name + ': binding ' + binding + ' is not a reviewed source')
    if set(found.get(name, ('',))[0] for name in found) - set(DOMAINS):
        problems.append('a kernel domain has no title')
    return problems


def cell(text):
    return text.replace('|', '\\|')


def page(manifest, found):
    total = len(manifest['sources'])
    by = counts(manifest)
    properties = sum(len(policy['theorems']) for policy in manifest['policies'].values())
    share = lambda n: f'{100 * n / total:.1f} %'
    lines = [
        '# What is proved, what is reviewed and what is neither',
        '',
        '<!-- Generated by scripts/formal/coverage_page.py from proof/manifest.json and crates/kernel/src/verified_kernel. Do not edit; run the script. -->',
        '',
        'This page answers one question per source file of the commerce core: is its',
        'rule proved by machine, does it call a proved rule, or neither? It is',
        'generated from the same manifest the proof check uses, so it cannot say more',
        'than the check verifies. **It is not a claim that the shop is free of errors:**',
        f'{share(by["unproved"])} of the Rust source files are unproved.',
        '',
        '## In numbers',
        '',
        '| | Count | Share of source files | Meaning |',
        '| --- | ---: | ---: | --- |',
        f'| **Proved rules** | {len(manifest["policies"])} | | Small pure decisions, translated from the production Rust source to Lean and proved there |',
        f'| **Proved properties** | {properties} | | Statements about those rules that hold for every possible input |',
        f'| Rule files | {by["extracted-policy"]} | {share(by["extracted-policy"])} | The files that contain the proved rules |',
        f'| Reviewed callers | {by["reviewed-binding"]} | {share(by["reviewed-binding"])} | Files that call a proved rule; a person reviewed how the rule is fed, the surrounding code is not proved |',
        f'| Comparison drivers | {by["conformance-driver"]} | {share(by["conformance-driver"])} | Test programs that compare the compiled Rust rules with the Lean versions |',
        f'| **Unproved files** | {by["unproved"]} | {share(by["unproved"])} | Everything else: database access, HTTP, providers, the user interface server |',
        f'| All Rust source files | {total} | 100 % | |',
        '',
        'A proved rule looks like this one, which caps a discount at the amount it is',
        'taken from:',
        '',
        '```rust',
        'pub fn discount_cap(total: u64, requested: u64) -> u64 {',
        '    total.min(requested)',
        '}',
        '```',
        '',
        'The proof covers that function for all inputs. It does not cover the SQL that',
        'reads the total, the request that carries the discount or the code that',
        'stores the result. [How the proofs connect to the application](formal-verification.md).',
        '',
        '## The money path',
        '',
        'These are the files a price, an order total or a payment passes through.',
        '"Uses floating point" counts files that contain the type `f64`; exact money',
        'arithmetic uses whole minor units instead, so each such file is a place where',
        'rounding still has to be argued by tests rather than by the type.',
        '',
        '| Area | Files | Call a proved rule | Unproved | Use floating point |',
        '| --- | ---: | ---: | ---: | ---: |',
    ]
    money_total = [0, 0, 0, 0]
    for title, belongs in MONEY:
        files = sorted(path for path in manifest['sources'] if belongs(path))
        bound = sum(manifest['sources'][path]['status'] == 'reviewed-binding' for path in files)
        unproved = sum(manifest['sources'][path]['status'] == 'unproved' for path in files)
        floating = sum(bool(re.search(r'\bf64\b', (ROOT / path).read_text())) for path in files)
        lines.append(f'| {title} | {len(files)} | {bound} | {unproved} | {floating} |')
        for index, value in enumerate((len(files), bound, unproved, floating)):
            money_total[index] += value
    lines += [
        f'| **Money path in total** | **{money_total[0]}** | **{money_total[1]}** | **{money_total[2]}** | **{money_total[3]}** |',
        '',
        'The money path is also checked by tests that are not shown here: the',
        'differential comparison against the original PHP price calculation and the',
        'registered HTTP and PostgreSQL suites. [Testing](testing.md) describes them.',
        'This page does not show test coverage per file.',
        '',
        '## Every proved rule',
        '',
        'Each rule links to its production source. "Used in" lists the reviewed files',
        'that call it.',
        '',
    ]
    for domain, title in DOMAINS.items():
        names = sorted(name for name, (owner, _) in found.items() if owner == domain)
        if not names:
            continue
        proved = sum(len(manifest['policies'][name]['theorems']) for name in names)
        lines += [
            f'### {title}',
            '',
            f'{len(names)} rules, {proved} proved properties.',
            f'[Source]({SOURCE}crates/kernel/src/verified_kernel/{domain}.rs).',
            '',
            '| Rule | What the source says about it | Proved properties | Used in |',
            '| --- | --- | --- | --- |',
        ]
        for name in names:
            policy = manifest['policies'][name]
            note = cell(found[name][1]) or 'No comment in the source'
            theorems = ', '.join(f'`{theorem}`' for theorem in policy['theorems'])
            used = ', '.join(f'`{binding}`' for binding in policy['bindings']) or 'No caller listed'
            lines.append(f'| `{name}` | {note} | {len(policy["theorems"])}: {theorems} | {used} |')
        lines.append('')
    lines += [
        '## How this page stays current',
        '',
        '`python3 scripts/formal/coverage_page.py` writes this page. The required quick',
        'check runs it with `--check` and fails when the page differs from the',
        'manifest, when a rule in the kernel is missing from the manifest, or when a',
        'listed rule has no proved property. Adding a source file therefore changes',
        'the numbers above in the same change.',
        '',
    ]
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail when the page differs from the manifest')
    args = parser.parse_args(argv)
    manifest = json.loads(MANIFEST.read_text())
    found = rules()
    problems = errors(manifest, found)
    if problems:
        raise SystemExit('\n'.join(problems))
    text = page(manifest, found)
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != text:
            raise SystemExit('docs/proof-coverage.md is stale; run python3 scripts/formal/coverage_page.py')
    else:
        PAGE.write_text(text)
        print('wrote', PAGE)
    # Negative controls: a rule without a property and a rule missing from the manifest must be rejected.
    broken = json.loads(json.dumps(manifest))
    first = next(iter(broken['policies']))
    broken['policies'][first]['theorems'] = []
    assert errors(broken, found), 'a rule without a proved property must fail'
    broken = json.loads(json.dumps(manifest))
    del broken['policies'][first]
    assert errors(broken, found), 'a kernel rule missing from the manifest must fail'
    by = counts(manifest)
    assert sum(by.values()) == len(manifest['sources'])
    print(f'PASS proof coverage page: {len(manifest["policies"])} rules, {by["reviewed-binding"]} reviewed callers, {by["unproved"]} unproved files; negative controls rejected')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
