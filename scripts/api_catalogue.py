#!/usr/bin/env python3
"""Generate a drift-checked static HTTP route catalogue from the compiled Rust router declarations."""
import json,re,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
rows={}
files=[*(ROOT/'src').rglob('*.rs')]
# Explicit native app mounts are compiled into the core; independent service routers stay excluded.
files.extend(ROOT/'extensions/apps/site-builder'/name for name in ['context.rs','design_agent.rs'])
for file in sorted(files):
 # Independently deployed app services are not core API endpoints.
 if 'connectors' in file.relative_to(ROOT).parts:continue
 text=file.read_text()
 for match in re.finditer(r'\.(?:route|secure_route)\(\s*"([^"\n]+)"\s*,',text):
  start=match.end();depth=1;quoted=False;escaped=False;end=start
  while end<len(text) and depth:
   c=text[end]
   if quoted:
    if escaped:escaped=False
    elif c=='\\':escaped=True
    elif c=='"':quoted=False
   elif c=='"':quoted=True
   elif c=='(':depth+=1
   elif c==')':depth-=1
   end+=1
  expression=text[start:end-1]
  for method in re.findall(r'\b(get|post|put|patch|delete|head|options)\s*\(',expression):
   path=match.group(1)
   rows[(path,method)]={'path':path,'method':method.upper(),'source':str(file.relative_to(ROOT))}
ordered=sorted(rows.values(),key=lambda r:(r['path'],r['method']))
source=('/** Generated by scripts/api_catalogue.py from the Rust router declarations; do not edit. */\n'
 '/** Every static route the server mounts, keyed "METHOD /path", with the Rust file that declares it. */\n'
 'export const routeSources = '+json.dumps({r['method']+' '+r['path']:r['source'] for r in ordered},indent=2)+' as const;\n'
 'export type RouteKey = keyof typeof routeSources;\n')
# Format with the frontend's Prettier so the committed file and the check agree byte for byte.
script="import prettier from 'prettier';let input='';for await(const c of process.stdin)input+=c;process.stdout.write(await prettier.format(input,{parser:'typescript'}));"
result=subprocess.check_output(['node','--input-type=module','-e',script],input=source.encode(),cwd=ROOT/'frontend').decode()
target=ROOT/'frontend/src/kit/api/generated/routes.ts'
if '--check' in sys.argv:
 if not target.exists() or target.read_text()!=result:sys.exit('API catalogue drift: run python3 scripts/api_catalogue.py')
else:
 target.parent.mkdir(parents=True,exist_ok=True);target.write_text(result)
print(f'API catalogue: {len(rows)} static route/method pairs; app routes are discovered per shop at runtime')
