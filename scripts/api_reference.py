#!/usr/bin/env python3
"""Generate the handbook API reference (docs/reference/) from the component contracts; `--check` fails on drift.

Development tooling only. Inputs, all generated or checked elsewhere:

- `contracts/http/<component>.openapi.json`: routes, permissions, sources and the typed MCP tools with
  their operation facts (scripts/sdks/contracts.py);
- `contracts/browser-reads.json`: the anonymous reads the server admits from any browser origin
  (src/browser_reads.rs) and the only operations a Try-it panel executes;
- the SDK naming rules in scripts/sdks/model.py, so every TypeScript, Python and Rust example names the
  method the generated SDK actually has.

    python3 scripts/api_reference.py           write docs/reference/*.md
    python3 scripts/api_reference.py --check   fail when a committed page differs from its generator

Examples, panels and tables are rendered from these inputs only; nothing here is written per operation.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts/sdks'))
from model import camel, pascal, snake  # noqa: E402

CONTRACTS = ROOT / 'contracts/http'
OUT = ROOT / 'docs/reference'
BROWSER = ROOT / 'contracts/browser-reads.json'
METHODS = ('get', 'post', 'put', 'patch', 'delete')
NOTICE = '<!-- Generated by scripts/api_reference.py from contracts/http; do not edit. -->'
SANDBOX = '../build-your-first-app.md#deploy-to-a-private-sandbox'


def browser_reads(paths):
    """The browser-read contract must name existing public routes only."""
    policy = json.loads(BROWSER.read_text())
    reads = {}
    for read in policy['reads']:
        method, path = read['method'].lower(), read['path']
        op = paths.get(path, {}).get(method)
        assert op, f'browser read {method.upper()} {path} is not a contract route'
        assert op.get('x-veyndo-permission') in (None, 'public'), f'browser read {path} is not public'
        reads[(method, path)] = read
    assert not {'authorization', 'cookie', 'sw-context-token'} & {h.lower() for h in policy['headers']}
    return reads


def permission_text(op):
    permission = op.get('x-veyndo-permission')
    if permission in (None, 'public'):
        return 'public, no credential'
    return f'`{permission}`, personal session or integration key'


def needs_auth(op):
    return op.get('x-veyndo-permission') not in (None, 'public')


def sample(schema, schemas, depth=0):
    """A minimal valid-looking value for a JSON schema: required fields only, documented bounds respected."""
    if '$ref' in schema:
        return sample(schemas[schema['$ref'].rsplit('/', 1)[1]], schemas, depth)
    kind = schema.get('type')
    if isinstance(kind, list):
        kind = next((k for k in kind if k != 'null'), None)
    if 'const' in schema:
        return schema['const']
    if 'enum' in schema:
        return schema['enum'][0]
    if kind == 'string':
        return '<string>'
    if kind == 'integer':
        return max(1, schema.get('minimum', 1)) if 'maximum' not in schema else min(max(1, schema.get('minimum', 1)), schema['maximum'])
    if kind == 'number':
        return schema.get('minimum', 1)
    if kind == 'boolean':
        return False
    if kind == 'array':
        return []
    if kind == 'object' and depth < 3:
        properties = schema.get('properties', {})
        value = {key: sample(properties[key], schemas, depth + 1) for key in schema.get('required', []) if key in properties}
        if not value and 'limit' in properties:
            value['limit'] = 3
        return value
    return {}


def type_text(schema, schemas):
    if '$ref' in schema:
        return type_text(schemas[schema['$ref'].rsplit('/', 1)[1]], schemas)
    kind = schema.get('type', 'any')
    if isinstance(kind, list):
        kind = ' or '.join(kind)
    if 'enum' in schema:
        return ' \\| '.join(f'`{json.dumps(v)}`' for v in schema['enum'])
    if kind == 'array':
        return 'array of ' + type_text(schema.get('items', {}), schemas)
    bounds = [f'{label} {schema[key]}' for key, label in [('minimum', '≥'), ('maximum', '≤'), ('minLength', 'min length'),
                                                         ('maxLength', 'max length'), ('maxItems', 'max items')] if key in schema]
    return kind + (f' ({", ".join(bounds)})' if bounds else '')


def placeholder(path):
    return {name: f'<{name}>' for name in [part[1:-1].lstrip('*') for part in path.split('/') if part.startswith('{')]}


def concrete(path, values):
    for name, value in values.items():
        path = path.replace('{' + name + '}', value).replace('{*' + name + '}', value)
    return path


def http_examples(component, method, path, op, body):
    """curl, TypeScript, Python and Rust calls of one route, in the generated SDKs' own names."""
    params = placeholder(path)
    name = op['operationId']
    auth = needs_auth(op)
    data = json.dumps(body, ensure_ascii=False) if body is not None else None
    curl = [f'curl -fsS -X {method.upper()} "$VEYNDO_URL{concrete(path, params)}" \\', '  -H "x-tenant: $VEYNDO_SHOP"']
    if auth:
        curl[-1] += ' \\'
        curl.append('  -H "authorization: Bearer $VEYNDO_TOKEN"')
    if data is not None:
        curl[-1] += ' \\'
        curl += ["  -H 'content-type: application/json' \\", f"  --data '{data}'"]
    ts_args = []
    if params:
        ts_args.append('{ ' + ', '.join(f'{json.dumps(k)}: {json.dumps(v)}' for k, v in params.items()) + ' }')
    if data is not None:
        ts_args.append(f'{{ body: {data} }}')
    ts = f'const result = await client.{camel(component)}.{name}({", ".join(ts_args)});'
    py_args = [json.dumps(v) for v in params.values()]
    if data is not None:
        py_args.append(f'body={python_literal(body)}')
    py = f'result = client.{snake(component)}.{snake(name)}({", ".join(py_args)})'
    rs_args = [json.dumps(v) for v in params.values()]
    rs_args.append(f'RequestOptions::json(json!({data}))' if data is not None else 'RequestOptions::default()')
    rs = f'let result = client.{snake(component)}().{snake(name)}({", ".join(rs_args)}).await?;'
    return {'curl': '\n'.join(curl), 'typescript': ts, 'python': py, 'rust': rs}


def python_literal(value):
    return json.dumps(value, ensure_ascii=False).replace('true', 'True').replace('false', 'False').replace('null', 'None')


def mcp_examples(tool, arguments):
    data = json.dumps(arguments, ensure_ascii=False)
    envelope = json.dumps({'jsonrpc': '2.0', 'id': 1, 'method': 'tools/call',
                           'params': {'name': tool['name'], 'arguments': arguments}}, ensure_ascii=False)
    curl = ['curl -fsS -X POST "$VEYNDO_URL/mcp" \\', '  -H "x-tenant: $VEYNDO_SHOP" \\']
    if tool['facts']['audience'] == 'merchant':
        curl.append('  -H "authorization: Bearer $VEYNDO_TOKEN" \\')
    curl += ["  -H 'content-type: application/json' \\", f"  --data '{envelope}'"]
    return {'curl': '\n'.join(curl),
            'typescript': f'const result = await client.mcp.call({json.dumps(tool["name"])}, {data});',
            'python': f'result = client.mcp.call({json.dumps(tool["name"])}, {python_literal(arguments)})',
            'rust': f'let result = client.mcp().call_raw({json.dumps(tool["name"])}, json!({data})).await?;'}


def example_block(examples):
    """Four labelled code blocks; docs-try.js turns them into tabs, and they stay readable without script."""
    parts = ['<div class="docs-examples" markdown="1">', '']
    for language, label in [('curl', 'curl'), ('typescript', 'TypeScript'), ('python', 'Python'), ('rust', 'Rust')]:
        fence = 'sh' if language == 'curl' else language
        parts += [f'<p class="docs-example-label">{label}</p>', '', f'```{fence}', examples[language], '```', '']
    parts += ['</div>', '']
    return parts


def attribute(value):
    return json.dumps(value, ensure_ascii=False).replace('&', '&amp;').replace("'", '&#39;')


def try_panel(method, path, body):
    params = list(placeholder(path))
    data = f" data-body='{attribute(body)}'" if body is not None else ''
    return [f'<div class="docs-try" data-method="{method.upper()}" data-path="{path}"'
            f" data-params='{attribute(params)}'{data}></div>", '']


def request_panel(lines):
    return [f'<p class="docs-try-note">{lines}</p>', '']


def route_section(component, method, path, op, browser):
    read = browser.get((method, path))
    body = read.get('body') if read else ({} if 'requestBody' in op else None)
    lines = [f'### `{method.upper()} {path}` {{: #{op["operationId"]} }}', '',
             f'Permission: {permission_text(op)}. Source: `{op["x-veyndo-source"]}`. '
             f'SDK method: `{op["operationId"]}`.', '']
    if read:
        lines += try_panel(method, path, body)
    elif method == 'get' and not needs_auth(op):
        lines += request_panel('Needs a cart, buyer or object token: run the example against your own shop.')
    elif method == 'get':
        lines += request_panel(f'Needs a merchant credential. Run it against your own <a href="{SANDBOX}">private sandbox</a>.')
    else:
        lines += request_panel(f'Not executed from the docs. Try it in a <a href="{SANDBOX}">private sandbox</a>.')
    return lines + example_block(http_examples(component, method, path, op, body))


def facts_table(tool):
    facts = tool['facts']
    data = facts['data']
    rows = [('Audience', facts['audience']), ('Writes', 'yes' if facts['writes'] else 'no'), ('Risk', facts['risk']),
            ('Reversibility', facts['reversibility']['kind']),
            ('Requires approval', 'yes' if tool['requiresApproval'] else 'no'), ('Cost', tool['cost']),
            ('Permissions', ', '.join(f'`{p}`' for p in facts['permissions']) or 'none'),
            ('Effects', ', '.join(facts['effects']) or 'none'),
            ('Conditions', ', '.join(facts['conditions']) or 'none'),
            ('Data', ', '.join(data['entities']) + ''.join(f' · {k}' for k in ('money', 'pii', 'stock') if data.get(k))),
            ('Requires', ', '.join(f'`{r}`' for r in facts['requires']) or 'none')]
    return ['| Fact | Value |', '| --- | --- |', *[f'| {k} | {v} |' for k, v in rows], '']


def input_table(schema, schemas):
    properties = schema.get('properties', {})
    if not properties:
        return ['Input: no arguments.', '']
    required = set(schema.get('required', []))
    rows = ['| Argument | Type | Required |', '| --- | --- | --- |']
    rows += [f'| `{key}` | {type_text(value, schemas)} | {"yes" if key in required else "no"} |' for key, value in properties.items()]
    return rows + ['']


def tool_section(tool, schemas):
    schema = schemas[tool['input']['$ref'].rsplit('/', 1)[1]]
    arguments = sample(schema, schemas)
    facts = tool['facts']
    lines = [f'### `{tool["name"]}` {{: #tool-{tool["name"].replace(".", "-")} }}', '', tool['description'].rstrip('.') + '.', '']
    lines += facts_table(tool) + input_table(schema, schemas)
    if facts['audience'] == 'shopper' and not facts['writes']:
        note = ('A shopper read. Browsers on other origins cannot call <code>POST /mcp</code> (it accepts only the '
                'shop&#39;s own origin); copy the request into your agent, server or terminal.')
    elif facts['writes']:
        note = f'A write. Not executed from the docs. Try it in a <a href="{SANDBOX}">private sandbox</a>.'
    else:
        note = f'Needs a merchant credential. Run it against your own <a href="{SANDBOX}">private sandbox</a>.'
    return lines + request_panel(note) + example_block(mcp_examples(tool, arguments))


def setup_block(component):
    return ['## Set up a client', '',
            'Every example below uses these three values. `VEYNDO_TOKEN` is needed only for merchant operations; '
            'keep it on your server.', '',
            '```sh', 'export VEYNDO_URL=https://api.veyndo.ai', 'export VEYNDO_SHOP=<your-shop-id>',
            'export VEYNDO_TOKEN=<personal-session-or-integration-key>', '```', '',
            *example_block({
                'curl': 'curl -fsS "$VEYNDO_URL/health"',
                'typescript': '\n'.join(['import { Auth, VeyndoClient } from "@veyndo/commerce-client";', '',
                                         'const client = new VeyndoClient({',
                                         '  baseUrl: process.env.VEYNDO_URL!,',
                                         '  tenant: process.env.VEYNDO_SHOP,',
                                         '  auth: process.env.VEYNDO_TOKEN ? Auth.personalSession(process.env.VEYNDO_TOKEN) : undefined,',
                                         '});']),
                'python': '\n'.join(['import os', 'from veyndo_sdk import Auth, VeyndoClient', '',
                                     'token = os.environ.get("VEYNDO_TOKEN")',
                                     'client = VeyndoClient(os.environ["VEYNDO_URL"], tenant=os.environ["VEYNDO_SHOP"],',
                                     '                      auth=Auth.personal_session(token) if token else None)']),
                'rust': '\n'.join(['use serde_json::json;', 'use veyndo_sdk::{Auth, Client, ClientOptions, RequestOptions};', '',
                                   'let client = Client::new(ClientOptions {',
                                   '    base_url: std::env::var("VEYNDO_URL")?,',
                                   '    tenant: std::env::var("VEYNDO_SHOP").ok(),',
                                   '    auth: std::env::var("VEYNDO_TOKEN").ok().map(Auth::PersonalSession),',
                                   '    ..ClientOptions::default()', '});'])}),
            f'The `{camel(component)}` API object, method names and argument order are those of the generated '
            '[SDKs](../sdks.md).', '']


def component_page(name, doc, browser):
    paths = doc['paths']
    schemas = doc['components']['schemas']
    info = doc['info']
    title = info['title'].split(': ', 1)[-1]
    store = [(m, p, o) for p, item in sorted(paths.items()) for m, o in item.items() if m in METHODS and not needs_auth(o)]
    merchant = [(m, p, o) for p, item in sorted(paths.items()) for m, o in item.items() if m in METHODS and needs_auth(o)]
    tools = sorted(doc['x-veyndo-tools'], key=lambda t: t['name'])
    lines = [f'# {pascal(name)} API reference', '', NOTICE, '',
             f'{title}. Contract version {info["version"]}, generated from '
             f'[`contracts/http/{name}.openapi.json`](../../contracts/http/{name}.openapi.json). '
             f'{len(store) + len(merchant)} HTTP operations, {len(tools)} MCP tools. '
             '[All components](README.md) · [Build your first app](../build-your-first-app.md).', '',
             '<div class="docs-try-config"></div>', '']
    lines += setup_block(name)
    lines += ['## Operations', '', '| Operation | Permission | In the docs |', '| --- | --- | --- |']
    for method, path, op in store + merchant:
        live = 'Try it' if (method, path) in browser else 'request'
        lines.append(f'| [`{method.upper()} {path}`](#{op["operationId"]}) | {op.get("x-veyndo-permission") or "public"} | {live} |')
    for tool in tools:
        lines.append(f'| [MCP `{tool["name"]}`](#tool-{tool["name"].replace(".", "-")}) | '
                     f'{", ".join(tool["facts"]["permissions"]) or tool["facts"]["audience"]} | request |')
    lines.append('')
    if store:
        lines += ['## Public HTTP', '', 'Anonymous storefront, discovery and protocol routes. Name the shop with `x-tenant`.', '']
        for method, path, op in store:
            lines += route_section(name, method, path, op, browser)
    if merchant:
        lines += ['## Merchant HTTP', '', 'Each route checks the named permission against your current membership.', '']
        for method, path, op in merchant:
            lines += route_section(name, method, path, op, browser)
    if tools:
        lines += ['## MCP tools', '', 'Called with JSON-RPC `tools/call` on `POST /mcp`. The facts come from the '
                  '[typed operations graph](../business-capabilities.md#the-typed-operations-graph); the server '
                  'validates the input schema before it runs a tool.', '']
        for tool in tools:
            lines += tool_section(tool, schemas)
    return '\n'.join(lines).rstrip() + '\n'


def index_page(docs, combined, browser):
    problem = combined['components']['schemas']['Problem']
    lines = ['# API reference', '', NOTICE, '',
             'Every HTTP route and MCP tool of Veyndo, per component, generated from the same contracts as the '
             f'[SDKs](../sdks.md). Contract set {combined["info"]["version"]}. Each operation shows its permission, '
             'its owning source file and a copyable call in curl, TypeScript, Python and Rust.', '',
             '## Try it from this page', '',
             'Public reads have a **Try it** panel. It calls the shop you enter below directly from your browser, '
             f'with no credential. The server admits exactly {len(browser)} anonymous reads from other origins '
             '([`contracts/browser-reads.json`](../../contracts/browser-reads.json)); everything else shows the '
             'request instead:', '',
             '- **Writes** are never executed from the docs. Use a [private sandbox](' + SANDBOX + ').',
             '- **Merchant reads** need your credential; the docs never ask for it.',
             '- **MCP tools** accept browser calls only from the shop’s own origin, so their panels show the '
             'JSON-RPC request to copy.', '',
             '<div class="docs-try-config"></div>', '',
             '## Components', '', '| Component | HTTP | MCP tools | Try it |', '| --- | ---: | ---: | ---: |']
    empty = []
    for name, doc in docs:
        routes = sum(1 for item in doc['paths'].values() for m in item if m in METHODS)
        tools = len(doc['x-veyndo-tools'])
        if not routes and not tools:
            empty.append(name)
            continue
        live = sum(1 for (m, p) in browser if p in doc['paths'] and m in doc['paths'][p])
        lines.append(f'| [{pascal(name)}]({name}.md) | {routes} | {tools} | {live} |')
    lines += ['', f'Components without a public surface: {", ".join(empty)}. They are called through the core.', '',
              '## Authentication', '',
              '| Credential | Header | Get it |', '| --- | --- | --- |',
              '| None (public) | `x-tenant: <shop id>` | The shop ID from Studio or your sandbox |',
              '| Personal session | `authorization: Bearer <token>` | `POST /api/auth/login` or `/api/auth/register` |',
              '| Integration key | `authorization: Bearer <key>` | **Developer → API & integrations**, server-side only |', '',
              '## Errors', '',
              'Every failure is `{"errors":[Problem, …]}` on HTTP and inside `structuredContent.errors` of an MCP result '
              'with `isError: true`. The SDKs raise both as one error type.', '',
              '| Problem field | Required |', '| --- | --- |']
    lines += [f'| `{key}` | {"yes" if key in problem["required"] else "no"} |' for key in problem['properties']]
    lines += ['', 'Kinds: ' + ', '.join(f'`{kind}`' for kind in problem['properties']['kind']['enum']) + '.', '',
              '## MCP tool catalog', '',
              'All native tools with their typed facts. Approval-required tools stop for a person before they run.', '',
              '| Tool | Component | Audience | Writes | Risk | Approval |', '| --- | --- | --- | --- | --- | --- |']
    rows = []
    for name, doc in docs:
        for tool in doc['x-veyndo-tools']:
            facts = tool['facts']
            rows.append((tool['name'], f'| [`{tool["name"]}`]({name}.md#tool-{tool["name"].replace(".", "-")}) | {name} | '
                         f'{facts["audience"]} | {"yes" if facts["writes"] else "no"} | {facts["risk"]} | '
                         f'{"yes" if tool["requiresApproval"] else "no"} |'))
    lines += [row for _, row in sorted(rows)]
    return '\n'.join(lines) + '\n'


def render():
    combined = json.loads((CONTRACTS / 'veyndo.openapi.json').read_text())
    browser = browser_reads(combined['paths'])
    docs = [(tag['name'], json.loads((CONTRACTS / f"{tag['name']}.openapi.json").read_text())) for tag in combined['tags']]
    files = {'docs/reference/README.md': index_page(docs, combined, browser)}
    for name, doc in docs:
        if doc['paths'] or doc['x-veyndo-tools']:
            files[f'docs/reference/{name}.md'] = component_page(name, doc, browser)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render()
    drift = [name for name, text in files.items() if not (ROOT / name).is_file() or (ROOT / name).read_text() != text]
    stale = sorted(p.relative_to(ROOT).as_posix() for p in OUT.glob('*.md') if p.relative_to(ROOT).as_posix() not in files) if OUT.exists() else []
    if args.check:
        if drift or stale:
            sys.exit('API reference drift: ' + ', '.join(drift + [s + ' (stale)' for s in stale]) +
                     ' (run python3 scripts/api_reference.py)')
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name in drift:
            (ROOT / name).write_text(files[name])
        for name in stale:
            (ROOT / name).unlink()
    print(f'PASS API reference: {len(files)} pages' + ('' if args.check else f' ({len(drift)} written, {len(stale)} removed)'))


if __name__ == '__main__':
    main()
