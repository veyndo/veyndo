"""Render the Python SDK (standard library `urllib` and dataclasses only) from the contract model.

Development tooling only; called by scripts/sdks/generate.py.
"""
import json

from model import Array, Const, Enum, Map, Nullable, Prim, Struct, pascal, snake

HEADER = '"""{0} Generated by scripts/sdks/python.py from contracts/http; do not edit."""\n'


def py_type(t):
    if isinstance(t, Prim):
        return {'string': 'str', 'integer': 'int', 'number': 'float', 'boolean': 'bool'}[t.name]
    if isinstance(t, Enum):
        return 'Literal[' + ', '.join(json.dumps(v) for v in t.values) + ']'
    if isinstance(t, Const):
        return f'Literal[{json.dumps(t.value)}]' if isinstance(t.value, (str, int, bool)) else 'Any'
    if isinstance(t, Array):
        return f'list[{py_type(t.item)}]'
    if isinstance(t, Map):
        return f'dict[str, {py_type(t.value)}]'
    if isinstance(t, Nullable):
        return f'Optional[{py_type(t.inner)}]'
    if isinstance(t, Struct):
        return t.name
    return 'Any'


def struct(s, tool_name=None):
    lines = ['@dataclass', f'class {s.name}:']
    lines.append(f'    """{"Input of" if tool_name else "Part of"} the `{tool_name or s.name}` tool contract."""')
    if tool_name:
        lines.append(f'    TOOL: ClassVar[str] = {json.dumps(tool_name)}')
    used = set()
    ordered = [f for f in s.fields if f.required] + [f for f in s.fields if not f.required]
    for f in ordered:
        name = snake(f.key)
        while name in used or name in ('extra', 'TOOL'):
            name += '_'
        used.add(name)
        if f.required:
            lines.append(f'    {name}: {py_type(f.type)} = field(metadata={{"json": {json.dumps(f.key)}}})')
        else:
            lines.append(f'    {name}: Optional[{py_type(f.type)}] = field(default=None, metadata={{"json": {json.dumps(f.key)}}})')
    if s.open:
        lines.append('    extra: dict[str, Any] = field(default_factory=dict, metadata={"extra": True})')
    if not s.fields and not s.open:
        lines.append('    pass')
    return '\n'.join(lines)


