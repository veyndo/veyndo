def render(contract):
    components = [c for c in contract.components if c.routes or c.tools]
    files = {'sdks/python/veyndo_sdk/runtime.py': runtime(contract), 'sdks/python/veyndo_sdk/tools.py': tools(contract),
             'sdks/python/veyndo_sdk/__init__.py': init(contract, components),
             'sdks/python/veyndo_sdk/components/__init__.py': HEADER.format('One module per component with HTTP routes.'),
             'sdks/python/pyproject.toml': pyproject(contract)}
    for c in components:
        files[f'sdks/python/veyndo_sdk/components/{c.name}.py'] = component(c)
    return files
