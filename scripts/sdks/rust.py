def runtime(contract):
    kinds = '\n'.join(f'    /// `{k}`\n    {pascal(k)},' for k in contract.problem_kinds)
    types = {'string': 'String', 'integer': 'i64', 'boolean': 'bool'}
    lines = []
    for name, required, kind in contract.problem_fields:
        typ = 'ProblemKind' if name == 'kind' else types[kind]
        lines.append(f'    /// `{name}`')
        if required:
            lines.append(f'    pub {snake(name)}: {typ},')
        else:
            lines.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
            lines.append(f'    pub {snake(name)}: Option<{typ}>,')
    return RUNTIME.replace('__KINDS__', kinds).replace('__PROBLEM__', '\n'.join(lines))


def component(c):
    cls = pascal(c.name) + 'Api'
    lines = [HEADER.format(f'HTTP routes of the {c.name} component: {doc(c.title)}.'),
             'use crate::runtime::{Client, Error, RequestOptions};', 'use reqwest::Method;', 'use serde_json::Value;', '',
             f'/// {doc(c.title)} (contract version {c.version}).', '#[derive(Debug)]', f'pub struct {cls}<\'a> {{',
             "    pub(crate) client: &'a Client,", '}', '', f'impl {cls}<\'_> {{']
    for r in c.routes:
        permission = f' · permission `{r.permission}`' if r.permission else ''
        args = ''.join(f', {snake(p)}: &str' for p in r.params)
        params = '&[' + ', '.join(f'({json.dumps(p)}, {snake(p)})' for p in r.params) + ']'
        lines += [f'    /// `{r.method} {r.path}`{permission}',
                  f'    pub async fn {snake(r.operation_id)}(&self{args}, options: RequestOptions) -> Result<Value, Error> {{',
                  f'        self.client.request(Method::{r.method}, {json.dumps(r.path)}, {params}, options).await',
                  '    }']
    lines.append('}')
    return '\n'.join(lines) + '\n'


def tools(contract):
    out = [HEADER.format('Typed inputs and declared outputs of every native MCP tool.'),
           'use crate::runtime::Tool;', 'use serde::{Deserialize, Serialize};', 'use serde_json::Value;',
           'use std::collections::BTreeMap;', '']
    catalog = []
    for c in contract.components:
        for t in c.tools:
            for s in t.structs:
                title = f'Input of `{t.name}`: {doc(t.description)}' if s is t.input else f'Part of the `{t.name}` contract.'
                out += [struct(s, title), '']
            output = rs_type(t.output) if t.output is not None else 'Value'
            out += [f'impl Tool for {t.input.name} {{', f'    const NAME: &\'static str = {json.dumps(t.name)};',
                    f'    type Output = {output};', '}', '']
            catalog.append(f'    ({json.dumps(t.name)}, {json.dumps(c.name)}, {"true" if t.read_only else "false"}),')
    out += ['/// Every tool: name, owning component and read-only hint.', 'pub const TOOLS: &[(&str, &str, bool)] = &[', *catalog, '];',
            '', '/// Keeps the map import used when no contract declares one.', 'pub type JsonMap = BTreeMap<String, Value>;']
    return '\n'.join(out) + '\n'


def lib(contract, components):
    lines = [HEADER.format('Veyndo client: one typed API object per component plus MCP.'),
             'pub mod components;', 'pub mod runtime;', 'pub mod tools;', '',
             'pub use runtime::{ApiError, Auth, Client, ClientOptions, Error, Mcp, Problem, ProblemKind, RequestOptions, Tool, collect_pages};',
             '', '/// Contract version the SDK was generated from.', f'pub const CONTRACT_VERSION: &str = {json.dumps(contract.version)};', '',
             'impl Client {']
    for c in components:
        lines += [f'    /// {doc(c.title)}', f'    pub fn {snake(c.name)}(&self) -> components::{snake(c.name)}::{pascal(c.name)}Api<\'_> {{',
                  f'        components::{snake(c.name)}::{pascal(c.name)}Api {{ client: self }}', '    }']
    lines.append('}')
    mods = [HEADER.format('One module per component with HTTP routes.')] + [f'pub mod {snake(c.name)};' for c in components]
    return '\n'.join(lines) + '\n', '\n'.join(mods) + '\n'


def cargo(contract):
    return f'''[package]
name = "veyndo-sdk"
version = "{contract.version}"
edition.workspace = true
license-file.workspace = true
description = "Typed Veyndo Commerce client generated from the component contracts (reqwest + serde)"

[dependencies]
reqwest.workspace = true
serde.workspace = true
serde_json.workspace = true
tokio.workspace = true

[[bin]]
name = "veyndo-sdk-smoke"
path = "smoke/main.rs"
'''


def render(contract):
    components = [c for c in contract.components if c.routes or c.tools]
    lib_rs, mod_rs = lib(contract, components)
    files = {'sdks/rust/Cargo.toml': cargo(contract), 'sdks/rust/src/lib.rs': lib_rs, 'sdks/rust/src/components/mod.rs': mod_rs,
             'sdks/rust/src/runtime.rs': runtime(contract), 'sdks/rust/src/tools.rs': tools(contract)}
    for c in components:
        files[f'sdks/rust/src/components/{snake(c.name)}.rs'] = component(c)
    return files
