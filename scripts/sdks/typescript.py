"""Render the TypeScript SDK (ESM, fetch, no runtime dependencies) from the contract model.

Development tooling only; called by scripts/sdks/generate.py. The output runs unbuilt on Node
with type stripping (erasable syntax only, `.ts` import specifiers) and builds to `dist/` with
`tsc`, which rewrites the specifiers.
"""
import json

from model import Array, Const, Enum, Json, Map, Nullable, Prim, Struct, camel, pascal

HEADER = '/** {0} Generated by scripts/sdks/typescript.py from contracts/http; do not edit. */\n'


def comment(text):
    return text.replace('*/', '*\\/')


def ts_type(t):
    if isinstance(t, Prim):
        return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean'}[t.name]
    if isinstance(t, Enum):
        return ' | '.join(json.dumps(v) for v in t.values) or 'never'
    if isinstance(t, Const):
        return json.dumps(t.value)
    if isinstance(t, Array):
        return f'Array<{ts_type(t.item)}>'
    if isinstance(t, Map):
        return f'{{ [key: string]: {ts_type(t.value)} }}'
    if isinstance(t, Nullable):
        return f'{ts_type(t.inner)} | null'
    if isinstance(t, Struct):
        return t.name
    return 'JsonValue'


def struct(s):
    lines = [f'export interface {s.name} {{']
    for f in s.fields:
        if f.description:
            lines.append(f'  /** {comment(f.description)} */')
        lines.append(f'  {json.dumps(f.key)}{"" if f.required else "?"}: {ts_type(f.type)};')
    if s.open:
        lines.append('  [key: string]: unknown;')
    lines.append('}')
    return '\n'.join(lines)


RUNTIME = '''/** Transport, authentication, typed failures, cursor pagination and MCP tool calls shared by every component client. Generated by scripts/sdks/typescript.py from contracts/http; do not edit. */
import type { ToolInputs, ToolName, ToolOutputs } from "./tools.ts";

/** Any JSON value the server accepts or returns. */
export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };

/** Both credentials are sent as `Authorization: Bearer`; the server tells them apart. */
export type Auth = { kind: "personalSession"; token: string } | { kind: "integrationKey"; key: string };
export const Auth = {
  /** A personal merchant session from `identity.postAuthLogin` or `identity.postAuthRegister`. */
  personalSession(token: string): Auth {
    return { kind: "personalSession", token };
  },
  /** A scoped integration key from `identity.postWorkspaceIntegrations`. Keep it server-side. */
  integrationKey(key: string): Auth {
    return { kind: "integrationKey", key };
  },
};

/** Failure kinds of the shared error envelope (components/core/src/failure.rs). */
export type ProblemKind = __KINDS__;

/** One entry of the `{"errors":[...]}` envelope every HTTP failure and MCP tool error carries. */
export interface Problem {
__PROBLEM__
}

/** An HTTP or MCP tool failure with the server's structured problems. */
export class VeyndoError extends Error {
  readonly status: number;
  readonly problems: Problem[];
  readonly body: unknown;
  constructor(status: number, problems: Problem[], body: unknown) {
    super(problems[0]?.detail ?? `Veyndo request failed with HTTP ${status}`);
    this.name = "VeyndoError";
    this.status = status;
    this.problems = problems;
    this.body = body;
  }
  /** The first problem's kind, for example `"revision_conflict"`. */
  get kind(): ProblemKind | undefined {
    return this.problems[0]?.kind;
  }
  /** Whether the server says repeating the same request can succeed. */
  get retryable(): boolean {
    return this.problems.some((problem) => problem.retryable);
  }
}

/** A JSON-RPC protocol error from `/mcp` (unknown tool, malformed call). */
export class McpProtocolError extends Error {
  readonly code: number;
  readonly data: unknown;
  constructor(code: number, message: string, data: unknown) {
    super(message);
    this.name = "McpProtocolError";
    this.code = code;
    this.data = data;
  }
}

export interface ClientOptions {
  /** Origin of the Veyndo server, for example `https://api.veyndo.ai`. */
  baseUrl: string;
  auth?: Auth;
  /** Shop ID sent as `x-tenant`. */
  tenant?: string;
  /** Sales channel sent as `sw-sales-channel-id`. */
  salesChannel?: string;
  /** Storefront cart/customer context sent as `sw-context-token`. */
  contextToken?: string;
  headers?: Record<string, string>;
  fetch?: typeof fetch;
}

export interface RequestOptions {
  body?: unknown;
  query?: Record<string, string | number | boolean | undefined>;
  headers?: Record<string, string>;
  signal?: AbortSignal;
}

function problemsOf(body: unknown): Problem[] {
  const errors = (body as { errors?: unknown } | null)?.errors;
  return Array.isArray(errors) ? (errors as Problem[]) : [];
}

function expand(path: string, params: Record<string, string>): string {
  return path.replace(/\\{(\\*?)(\\w+)\\}/g, (_, wildcard: string, name: string) => {
    const value = params[name];
    if (value === undefined) throw new TypeError(`Missing path parameter ${name}`);
    return wildcard ? value.split("/").map(encodeURIComponent).join("/") : encodeURIComponent(value);
  });
}

/** Sends one request with the configured shop, channel, context and credential. */
export class Transport {
  readonly options: ClientOptions;
  constructor(options: ClientOptions) {
    this.options = options;
  }
  async request(method: string, path: string, params: Record<string, string>, options: RequestOptions = {}): Promise<JsonValue> {
    const url = new URL(expand(path, params), this.options.baseUrl);
    for (const [key, value] of Object.entries(options.query ?? {})) {
      if (value !== undefined) url.searchParams.set(key, String(value));
    }
    const headers: Record<string, string> = { accept: "application/json", ...this.options.headers };
    const auth = this.options.auth;
    if (auth) headers.authorization = `Bearer ${auth.kind === "personalSession" ? auth.token : auth.key}`;
    if (this.options.tenant) headers["x-tenant"] = this.options.tenant;
    if (this.options.salesChannel) headers["sw-sales-channel-id"] = this.options.salesChannel;
    if (this.options.contextToken) headers["sw-context-token"] = this.options.contextToken;
    let body: string | undefined;
    if (options.body !== undefined) {
      headers["content-type"] = "application/json";
      body = JSON.stringify(options.body);
    }
    const response = await (this.options.fetch ?? fetch)(url, {
      method,
      headers: { ...headers, ...options.headers },
      body,
      signal: options.signal,
    });
    const text = await response.text();
    let value: unknown = text;
    if ((response.headers.get("content-type") ?? "").includes("json") && text) value = JSON.parse(text);
    if (!text) value = null;
    if (!response.ok) throw new VeyndoError(response.status, problemsOf(value), value);
    return value as JsonValue;
  }
}

export interface PageOptions {
  /** Key of the item array in each page; default `elements`. */
  items?: string;
  /** Stop after this many pages; default 1000. */
  maxPages?: number;
}

/**
 * Yields every item of a cursor-paginated read. `fetchPage` receives the previous page's
 * `nextCursor` (undefined first) and passes it as the route's cursor field (`after` for
 * catalogue, product and customer lists). Stops when `nextCursor` is absent or `hasMore` is false.
 */
export async function* paginate(
  fetchPage: (cursor: string | undefined) => Promise<JsonValue>,
  options: PageOptions = {},
): AsyncGenerator<JsonValue> {
  let cursor: string | undefined;
  for (let page = 0; page < (options.maxPages ?? 1000); page++) {
    const value = (await fetchPage(cursor)) as { [key: string]: JsonValue };
    const items = value[options.items ?? "elements"];
    if (Array.isArray(items)) yield* items;
    const next = value.nextCursor;
    if (next === null || next === undefined || value.hasMore === false) return;
    cursor = String(next);
  }
}

/** Typed result of a tool: its declared output schema, otherwise any JSON. */
export type ToolOutput<N extends ToolName> = N extends keyof ToolOutputs ? ToolOutputs[N] : JsonValue;

/** JSON-RPC 2.0 calls to `POST /mcp` with the client's shop and credential. */
export class Mcp {
  readonly transport: Transport;
  #id = 0;
  constructor(transport: Transport) {
    this.transport = transport;
  }
  async rpc(method: string, params?: unknown): Promise<JsonValue> {
    const message = { jsonrpc: "2.0", id: ++this.#id, method, ...(params === undefined ? {} : { params }) };
    const reply = (await this.transport.request("POST", "/mcp", {}, { body: message })) as {
      result?: JsonValue;
      error?: { code: number; message: string; data?: unknown };
    };
    if (reply.error) throw new McpProtocolError(reply.error.code, reply.error.message, reply.error.data);
    return reply.result ?? null;
  }
  /** The tools the current credential may call in the selected shop. */
  async listTools(): Promise<Array<{ name: string; description?: string; inputSchema?: JsonValue }>> {
    const result = (await this.rpc("tools/list")) as { tools?: Array<{ name: string }> };
    return result.tools ?? [];
  }
  /** Calls a native tool; a tool error becomes a `VeyndoError` with its structured problems. */
  async call<N extends ToolName>(name: N, args: ToolInputs[N]): Promise<ToolOutput<N>> {
    const result = (await this.rpc("tools/call", { name, arguments: args })) as {
      isError?: boolean;
      structuredContent?: JsonValue;
      content?: Array<{ type: string; text?: string }>;
    };
    if (result.isError) {
      const problems = problemsOf(result.structuredContent);
      throw new VeyndoError(problems[0]?.status ?? 400, problems, result);
    }
    return (result.structuredContent ?? result) as ToolOutput<N>;
  }
}
'''


def runtime(contract):
    kinds = ' | '.join(json.dumps(k) for k in contract.problem_kinds)
    types = {'string': 'string', 'integer': 'number', 'boolean': 'boolean'}
    fields = '\n'.join(f'  {name}{"" if required else "?"}: {"ProblemKind" if name == "kind" else types[kind]};'
                       for name, required, kind in contract.problem_fields)
    return RUNTIME.replace('__KINDS__', kinds).replace('__PROBLEM__', fields)


def component(c):
    cls = pascal(c.name) + 'Api'
    lines = [HEADER.format(f'HTTP routes of the {c.name} component: {comment(c.title)}.'),
             'import type { JsonValue, RequestOptions, Transport } from "../runtime.ts";', '',
             f'/** {comment(c.title)} (contract version {c.version}). */', f'export class {cls} {{',
             '  readonly #transport: Transport;', '  constructor(transport: Transport) {', '    this.#transport = transport;', '  }']
    for r in c.routes:
        permission = f' · permission `{r.permission}`' if r.permission else ''
        lines.append(f'  /** `{r.method} {r.path}`{permission} */')
        if r.params:
            shape = '{ ' + '; '.join(f'{json.dumps(p)}: string' for p in r.params) + ' }'
            lines.append(f'  {r.operation_id}(params: {shape}, options?: RequestOptions): Promise<JsonValue> {{')
            lines.append(f'    return this.#transport.request({json.dumps(r.method)}, {json.dumps(r.path)}, params, options);')
        else:
            lines.append(f'  {r.operation_id}(options?: RequestOptions): Promise<JsonValue> {{')
            lines.append(f'    return this.#transport.request({json.dumps(r.method)}, {json.dumps(r.path)}, {{}}, options);')
        lines.append('  }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def tools(contract):
    out = [HEADER.format('Typed inputs and declared outputs of every native MCP tool.'),
           'import type { JsonValue } from "./runtime.ts";', '']
    inputs, outputs, meta = [], [], []
    for c in contract.components:
        for t in c.tools:
            for s in t.structs:
                out.append(f'/** {"Input" if s.name.startswith(pascal(t.name) + "Input") else "Output"} of `{t.name}`. */')
                out.append(struct(s))
                out.append('')
            inputs.append(f'  {json.dumps(t.name)}: {t.input.name};')
            if t.output is not None:
                outputs.append(f'  {json.dumps(t.name)}: {ts_type(t.output)};')
            meta.append(f'  {json.dumps(t.name)}: {{ component: {json.dumps(c.name)}, readOnly: {"true" if t.read_only else "false"}, description: {json.dumps(t.description)} }},')
    out += ['/** Tool name -> input type. */', 'export interface ToolInputs {', *inputs, '}', '',
            '/** Tool name -> declared output type (tools without a declared output return any JSON). */',
            'export interface ToolOutputs {', *outputs, '}', '', 'export type ToolName = keyof ToolInputs;', '',
            '/** Owning component, read-only hint and description of every tool. */',
            'export const toolCatalog = {', *meta, '} as const;',
            '', '/** Unused import guard for tools without declared outputs. */', 'export type ToolJson = JsonValue;']
    return '\n'.join(out) + '\n'


def index(contract, components):
    lines = [HEADER.format('Veyndo client: one typed API object per component plus MCP.')]
    lines.append('import { Mcp, Transport, type ClientOptions } from "./runtime.ts";')
    for c in components:
        lines.append(f'import {{ {pascal(c.name)}Api }} from "./components/{c.name}.ts";')
    lines += ['export * from "./runtime.ts";', 'export * from "./tools.ts";']
    for c in components:
        lines.append(f'export {{ {pascal(c.name)}Api }} from "./components/{c.name}.ts";')
    lines += ['', f'/** Contract version the SDK was generated from. */', f'export const contractVersion = {json.dumps(contract.version)};', '',
              '/** Calls Veyndo over HTTP and MCP with one shop, channel and credential. */', 'export class VeyndoClient {',
              '  readonly transport: Transport;', '  readonly mcp: Mcp;']
    for c in components:
        lines.append(f'  readonly {camel(c.name)}: {pascal(c.name)}Api;')
    lines += ['  constructor(options: ClientOptions) {', '    this.transport = new Transport(options);', '    this.mcp = new Mcp(this.transport);']
    for c in components:
        lines.append(f'    this.{camel(c.name)} = new {pascal(c.name)}Api(this.transport);')
    lines += ['  }', '  /** A client with some options replaced, for example another credential or cart context. */',
              '  with(options: Partial<ClientOptions>): VeyndoClient {', '    return new VeyndoClient({ ...this.transport.options, ...options });', '  }', '}']
    return '\n'.join(lines) + '\n'


def package(contract):
    return json.dumps({
        'name': '@veyndo/commerce-client',
        'version': contract.version,
        'description': 'Typed Veyndo Commerce client generated from the component contracts (fetch, no runtime dependencies).',
        'license': 'SEE LICENSE IN ../../LICENSE',
        'type': 'module',
        'exports': {'.': {'types': './dist/index.d.ts', 'import': './dist/index.js'}},
        'files': ['dist'],
        'scripts': {'build': 'tsc -p tsconfig.build.json', 'typecheck': 'tsc -p tsconfig.json', 'smoke': 'node tests/smoke.ts'},
        'engines': {'node': '>=22.18'},
    }, indent=2) + '\n'


COMPILER = {
    'target': 'ES2022', 'module': 'NodeNext', 'moduleResolution': 'NodeNext', 'lib': ['ES2022', 'DOM'],
    'strict': True, 'erasableSyntaxOnly': True, 'verbatimModuleSyntax': True, 'skipLibCheck': True,
}
# Type-check everything (sources, examples, smoke test) without emitting.
TSCONFIG = json.dumps({'compilerOptions': {**COMPILER, 'noEmit': True, 'allowImportingTsExtensions': True},
                       'include': ['src', 'examples', 'tests']}, indent=2) + '\n'
# Build only the package sources to dist/, rewriting the `.ts` import specifiers to `.js`.
TSCONFIG_BUILD = json.dumps({'compilerOptions': {**COMPILER, 'rewriteRelativeImportExtensions': True, 'declaration': True,
                                                 'rootDir': 'src', 'outDir': 'dist'},
                             'include': ['src']}, indent=2) + '\n'


def render(contract):
    components = [c for c in contract.components if c.routes or c.tools]
    files = {'sdks/typescript/src/runtime.ts': runtime(contract), 'sdks/typescript/src/tools.ts': tools(contract),
             'sdks/typescript/src/index.ts': index(contract, components),
             'sdks/typescript/package.json': package(contract), 'sdks/typescript/tsconfig.json': TSCONFIG,
             'sdks/typescript/tsconfig.build.json': TSCONFIG_BUILD}
    for c in components:
        files[f'sdks/typescript/src/components/{c.name}.ts'] = component(c)
    return files
