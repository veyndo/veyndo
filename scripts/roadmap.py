"""Render the one roadmap source into the handbook page, the README line and the website data module; --check rejects drift."""
from pathlib import Path
import argparse, json, re, sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/roadmap.json'
PAGE = ROOT / 'docs/roadmap.md'
README = ROOT / 'README.md'
START, END = '<!-- roadmap:start -->', '<!-- roadmap:end -->'
LOCALES = ('en', 'de', 'fr', 'es')
DONE = ('local', 'hosted')


def load(path=SOURCE):
    data = json.loads(path.read_text())
    errors = validate(data, path.parent.parent)
    if errors:
        raise SystemExit('\n'.join(errors))
    return data


def validate(data, root=ROOT):
    errors, seen = [], set()
    statuses = data.get('statuses', {})
    for name in ('thesis',):
        if set(data.get(name, {})) != set(LOCALES):
            errors.append(f'{name} needs exactly {LOCALES}')
    for key, labels in statuses.items():
        if set(labels) != set(LOCALES):
            errors.append(f'status {key} needs exactly {LOCALES}')
    for stage in data.get('stages', []):
        sid = stage.get('id', '')
        if not re.fullmatch(r'[a-z][a-z0-9-]{2,40}', sid) or sid in seen:
            errors.append(f'stage id {sid!r} must be unique kebab-case')
        seen.add(sid)
        if stage.get('status') not in statuses:
            errors.append(f'{sid}: unknown status {stage.get("status")!r}')
        for field in ('title', 'summary'):
            text = stage.get(field, {})
            if set(text) != set(LOCALES) or not all(isinstance(v, str) and v.strip() for v in text.values()):
                errors.append(f'{sid}: {field} needs non-empty {LOCALES}')
        if not stage.get('buildsOn'):
            errors.append(f'{sid}: buildsOn is required')
        for field in ('guide', 'evidence'):
            target = stage.get(field)
            if target and not (root / target.split('#')[0]).is_file():
                errors.append(f'{sid}: {field} {target} does not exist')
        # A stage that claims to work must say where to try it and what was observed.
        if stage.get('status') in DONE and not (stage.get('guide') and stage.get('evidence')):
            errors.append(f'{sid}: status {stage["status"]} requires a guide and dated evidence')
    return errors


def page(data):
    lines = [
        '# Roadmap: the shop that changes itself',
        '',
        '<!-- Generated by scripts/roadmap.py from docs/roadmap.json. Edit the JSON, then run the script. -->',
        '',
        f'**{data["thesis"]["en"]}** Every stage below reuses the existing core,',
        'private sandboxes and review. A stage counts as working only when it has a',
        'guide and a dated record of what was observed. The [status page](status.md)',
        'stays the record of what is deployed.',
        '',
        '| # | Stage | State | What it does | Builds on |',
        '| --- | --- | --- | --- | --- |',
    ]
    for index, stage in enumerate(data['stages'], 1):
        title = stage['title']['en']
        if stage.get('guide'):
            title = f'[{title}]({relative(stage["guide"])})'
        state = data['statuses'][stage['status']]['en']
        if stage.get('evidence'):
            state += f' ([record]({relative(stage["evidence"])}))'
        lines.append(f'| {index} | **{title}** | {state} | {stage["summary"]["en"]} | {stage["buildsOn"]} |')
    lines += [
        '',
        '## How this page stays current',
        '',
        'The stages live in one file, [`docs/roadmap.json`](roadmap.json), in English,',
        'German, French and Spanish. `python3 scripts/roadmap.py` writes this page,',
        'the roadmap line in the README and the data module the website reads.',
        'The required quick check runs `python3 scripts/roadmap.py --check` and fails',
        'when any of them differs from the file, or when a stage claims to work',
        'without a guide and a dated record.',
        '',
    ]
    return '\n'.join(lines)


def relative(target):
    return target[5:] if target.startswith('docs/') else '../' + target


def readme_block(data):
    done = sum(stage['status'] in DONE for stage in data['stages'])
    return (f'{START}\n**Roadmap:** {done} of {len(data["stages"])} stages work today. '
            f'[See what comes next](docs/roadmap.md).\n{END}')


def readme(data, text):
    if START not in text or END not in text:
        raise SystemExit('README.md needs the roadmap markers')
    return re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: readme_block(data), text, flags=re.S)


def site_module(data):
    public = {
        'thesis': data['thesis'],
        'statuses': data['statuses'],
        'stages': [{k: stage[k] for k in ('id', 'status', 'title', 'summary')} | {'guide': stage.get('guide')} for stage in data['stages']],
    }
    return ('// Generated by scripts/roadmap.py in veyndo/veyndo from docs/roadmap.json. Do not edit.\n'
            f'export default {json.dumps(public, ensure_ascii=False, indent=2)};\n')


def outputs(data, site=None):
    result = {PAGE: page(data), README: readme(data, README.read_text())}
    if site:
        result[Path(site) / 'js/roadmap-data.js'] = site_module(data)
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail when a generated file differs')
    parser.add_argument('--site', help='website source directory that receives js/roadmap-data.js')
    parser.add_argument('--print-site-module', action='store_true', help='print the website data module')
    args = parser.parse_args(argv)
    data = load()
    if args.print_site_module:
        sys.stdout.write(site_module(data))
        return 0
    stale = []
    for path, text in outputs(data, args.site).items():
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            stale.append(str(path))
        else:
            path.write_text(text)
            print('wrote', path)
    if stale:
        raise SystemExit('Roadmap outputs are stale; run python3 scripts/roadmap.py: ' + ', '.join(stale))
    # Negative controls: a claimed stage without proof and a missing translation must be rejected.
    broken = json.loads(json.dumps(data))
    broken['stages'][0].update(status='local', guide=None, evidence=None)
    assert validate(broken), 'claimed stage without guide/evidence must fail'
    broken = json.loads(json.dumps(data))
    del broken['stages'][0]['title']['es']
    assert validate(broken), 'missing translation must fail'
    print(f'PASS roadmap: {len(data["stages"])} stages, outputs current, negative controls rejected')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
